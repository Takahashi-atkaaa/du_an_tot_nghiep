<p style="margin-top: 10px; font-size: 11px; color: #666;">
    <strong>Hướng dẫn (cột đánh dấu * là bắt buộc, các cột khác chỉ để tham khảo):</strong><br>
    <br>
    <strong>1. Cách xác định biến thể khi nhập:</strong><br>
    - Mỗi sản phẩm có 1 hoặc nhiều <strong>biến thể</strong>. Cột <strong>Ten_bien_the</strong> + <strong>Thuoc_tinh</strong> dùng để phân biệt biến thể (ví dụ: XL + Đen là biến thể khác với L + Đen).<br>
    - Mỗi biến thể có mã vạch riêng lưu ở cột <strong>Ma_vach</strong>.<br>
    - Xem thông tin biến thể + mã vạch tại trang <em>Quản lý sản phẩm</em> trước khi nhập.<br>
    <br>
    <strong>2. Ý nghĩa từng cột:</strong><br>
    - <strong>Ma_vach *</strong>: Mã vạch sản phẩm (bắt buộc). Là mã vạch biến thể (đơn vị cơ bản) HOẶC mã vạch đơn vị quy đổi (Thùng, Hộp...). Hệ thống tự tìm.<br>
    - <strong>Ten_san_pham</strong>: Tên sản phẩm cha. Chỉ tham khảo, có thể để trống.<br>
    - <strong>Ten_bien_the</strong>: Tên biến thể (size, dung tích...). Để trống nếu sản phẩm chỉ có 1 biến thể.<br>
    - <strong>Thuoc_tinh</strong>: Các thuộc tính của biến thể (màu sắc, hương vị...). Để trống nếu sản phẩm không có thuộc tính.<br>
    - <strong>Ten_don_vi</strong>: Tên đơn vị quy đổi (Thùng x20, Hộp 10 viên...). Để trống nếu nhập theo đơn vị cơ bản.<br>
    - <strong>So_luong *</strong>: Số nguyên dương. Là số lượng theo đơn vị của Ma_vach. Nếu Ma_vach là Thùng (x20) thì So_luong = 5 nghĩa là 5 thùng.<br>
    - <strong>Gia_nhap *</strong>: Giá theo đơn vị của Ma_vach. Nếu Ma_vach là Thùng thì nhập giá/thùng.<br>
    - <strong>Han_su_dung</strong>: Định dạng YYYY-MM-DD hoặc DD/MM/YYYY. Bỏ trống = mặc định 2099-12-31.<br>
    <br>
    <strong>3. Quy tắc import:</strong><br>
    - Các dòng trùng Ma_vach + Han_su_dung sẽ tự động gộp (cộng dồn số lượng, tính lại giá nhập bình quân gia quyền).<br>
    - Hệ thống tự quy đổi về đơn vị cơ bản khi lưu kho (nhân So_luong với ty_le_quy_doi).<br>
    - Dòng trống sẽ bị bỏ qua.<br>
    <br>
    <strong>4. Giải thích 3 sản phẩm mẫu:</strong><br>
    - <em>Sản phẩm 1 (Áo thun)</em>: 6 biến thể (XL/L × Đen/Trắng/Xanh) + 1 đơn vị quy đổi Thùng x20. Mỗi dòng 1-6 nhập theo biến thể; dòng 7 nhập theo Thùng.<br>
    - <em>Sản phẩm 2 (Vitamin C)</em>: 1 biến thể duy nhất, có 2 đơn vị quy đổi (Hộp 10 viên, Hộp 30 viên). Dòng 1 nhập theo viên lẻ; dòng 2-3 nhập theo hộp.<br>
    - <em>Sản phẩm 3 (Sữa tươi)</em>: 1 biến thể, không có đơn vị quy đổi. Nhập trực tiếp theo hộp.
